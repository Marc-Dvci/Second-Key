// Runs the frozen scam-script table over the case set and writes docs/evaluation.md.
// Usage: npm run evaluate
import { readFileSync, writeFileSync } from 'node:fs';
import { matchScripts } from '../src/core/rules.ts';
import type { PayeeKind } from '../src/core/request.ts';

type Case = {
  id: string;
  kind: 'scam' | 'ordinary';
  family: string;
  title: string;
  source_name: string;
  source_url: string;
  answers: { payee_kind: PayeeKind; contacted_first: boolean; hurry: boolean; authority: boolean; secrecy: boolean };
};

const root = new URL('..', import.meta.url);
const { cases } = JSON.parse(readFileSync(new URL('cases/cases.json', root), 'utf8')) as { cases: Case[] };

type Row = Case & { scripts: string[]; main: string; named: boolean; correct: boolean };

const rows: Row[] = cases.map((c) => {
  const matched = matchScripts({
    payeeKind: c.answers.payee_kind,
    answers: {
      contactedFirst: c.answers.contacted_first,
      hurry: c.answers.hurry,
      authority: c.answers.authority,
      secrecy: c.answers.secrecy,
    },
  });
  const main = matched.find((s) => s.named);
  return {
    ...c,
    scripts: matched.map((s) => s.id),
    main: main?.name ?? '',
    named: Boolean(main),
    correct: Boolean(main && main.families.includes(c.family)),
  };
});

const scams = rows.filter((r) => r.kind === 'scam');
const ordinary = rows.filter((r) => r.kind === 'ordinary');
const count = (list: Row[], f: (r: Row) => boolean) => list.filter(f).length;

const flagged = count(scams, (r) => r.scripts.length > 0);
const correct = count(scams, (r) => r.correct);
const quiet = count(ordinary, (r) => r.scripts.length === 0);

const domains = [...new Set(scams.map((r) => new URL(r.source_url).hostname.replace(/^www\./, '')))].sort();
const families = [...new Set(scams.map((r) => r.family))];
const familyLines = families.map((f) => {
  const list = scams.filter((r) => r.family === f);
  return `| ${f.replace(/_/g, ' ')} | ${list.length} | ${count(list, (r) => r.correct)} |`;
});

const caseLines = rows.map((r) => {
  const source = r.source_url ? `[${r.source_name}](${r.source_url})` : 'constructed';
  const outcome = r.kind === 'scam' ? (r.correct ? 'named' : r.scripts.length ? 'flagged, other script' : 'missed') : r.scripts.length ? 'flagged' : 'no script';
  return `| ${r.id} | ${r.family.replace(/_/g, ' ')} | ${r.title} | ${r.main || r.scripts.join(', ') || '–'} | ${outcome} | ${source} |`;
});

const md = `# Evaluation: scam scripts on public cases

Generated by \`npm run evaluate\` from \`cases/cases.json\`. Do not edit by hand.

The case set has ${scams.length} scam cases, each paraphrased from a public warning page (${domains.join(', ')}), and ${ordinary.length} ordinary payments to a new payee. For every case, the answers a person would give at the moment of paying (payee type and the four yes/no questions) were filled in from the narrative by a separate pass that did not see the script table. The script table was committed (\`Add scam script table\`) before the cases were added to the repository.

## Results

| Measure | Result |
|---|---|
| Scam cases where the main script names the right family | **${correct} of ${scams.length}** |
| Scam cases with at least one script raised | ${flagged} of ${scams.length} |
| Ordinary payments with no script raised | ${quiet} of ${ordinary.length} |

Every request to someone new goes to the second key whatever the scripts say. A script briefs the call; it never approves or blocks a payment.

## By scam family

| Family | Cases | Named correctly |
|---|---|---|
${familyLines.join('\n')}

## Every case

| Id | Family | Case | Main script | Outcome | Source |
|---|---|---|---|---|---|
${caseLines.join('\n')}
`;

writeFileSync(new URL('docs/evaluation.md', root), md);
console.log(`Scam cases named correctly: ${correct}/${scams.length}`);
console.log(`Scam cases with any script: ${flagged}/${scams.length}`);
console.log(`Ordinary payments with no script: ${quiet}/${ordinary.length}`);
for (const r of rows) if ((r.kind === 'scam' && !r.correct) || (r.kind === 'ordinary' && r.scripts.length)) console.log(`  ${r.id} ${r.kind}: ${r.title} -> ${r.scripts.join(', ') || 'none'}`);
